/** True se a senha está na lista (sem diferenciar maiúsculas de minúsculas). */
export function isCommonPassword(password: string): boolean {
  return COMMON_PASSWORDS.has(password.trim().toLowerCase())
}

// Caminhos do Better Auth que gravam uma senha nova. Os de troca e redefinição
// ficam desligados (DISABLED_PATHS) ou sem tela; seguem na lista para o dia em
// que ligarem.
const PASSWORD_WRITE_PATHS = new Set([
  '/sign-up/email',
  '/change-password',
  '/set-password',
  '/reset-password',
  '/email-otp/reset-password',
])

/**
 * Lança 400 `PASSWORD_TOO_COMMON` se o pedido grava uma senha da lista.
 * Sem senha ligada, não faz nada (o login por código não tem senha).
 */
export function assertPasswordNotCommon(
  path: string,
  body: unknown,
  passwordLoginEnabled: boolean,
): void {
  if (!passwordLoginEnabled || !PASSWORD_WRITE_PATHS.has(path)) return
  const record = (body && typeof body === 'object' ? body : {}) as Record<
    string,
    unknown
  >
  const candidates = [record.password, record.newPassword]
  for (const value of candidates) {
    if (typeof value === 'string' && isCommonPassword(value)) {
      throw new APIError('BAD_REQUEST', {
        message: 'Senha comum demais. Escolha outra.',
        code: 'PASSWORD_TOO_COMMON',
      })
    }
  }
}
